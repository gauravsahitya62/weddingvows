function wvn_commercial_new_page_content($content) {
    if (is_admin() || !is_page()) {
        return $content;
    }
    $slug = get_post_field('post_name', get_queried_object_id());
    $pages = wvn_commercial_seo_pages();
    if (!isset($pages[$slug]) || strpos($content, 'wvn-commercial-content') !== false) {
        return $content;
    }

    $cfg = $pages[$slug];
    $html = '<div class="wvn-commercial-content">';
    foreach ($cfg['sections'] as $section) {
        $html .= '<section class="wvn-commercial-section">';
        $html .= '<h2 class="wvn-display">' . wp_kses_post($section['h']) . '</h2>';
        $html .= '<div class="wvn-commercial-copy"><p>' . wp_kses_post($section['p']) . '</p></div>';
        $html .= '</section>';
    }
    $html .= '</div>';
    return $html . $content;
}
add_filter('the_content', 'wvn_commercial_new_page_content', 31);

function wvn_commercial_meta_data() {
    if (!is_page()) {
        return null;
    }
    $slug = get_post_field('post_name', get_queried_object_id());
    $pages = wvn_commercial_seo_pages();
    return isset($pages[$slug]) ? $pages[$slug] : null;
}

