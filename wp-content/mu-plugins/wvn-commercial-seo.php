function wvn_commercial_head_schema() {
    $cfg = wvn_commercial_meta_data();
    if (!$cfg) {
        return;
    }
    $url = trailingslashit(get_permalink());
    $faq_entities = array();
    foreach ($cfg['faqs'] as $faq) {
        $faq_entities[] = array(
            '@type' => 'Question',
            'name' => $faq['q'],
            'acceptedAnswer' => array('@type' => 'Answer', 'text' => $faq['a']),
        );
    }
    $schema = array(
        '@context' => 'https://schema.org',
        '@graph' => array(
            array(
                '@type' => 'WebPage',
                '@id' => $url . '#webpage',
                'url' => $url,
                'name' => $cfg['title'],
                'description' => $cfg['description'],
                'inLanguage' => 'en-IN',
                'about' => array('@type' => 'Place', 'name' => 'Udaipur, Rajasthan'),
            ),
            array(
                '@type' => 'Service',
                '@id' => $url . '#service',
                'name' => $cfg['title'],
                'serviceType' => $cfg['title'],
                'description' => $cfg['description'],
                'url' => $url,
                'areaServed' => array('@type' => 'City', 'name' => 'Udaipur'),
                'provider' => array('@id' => trailingslashit(home_url('/')) . '#organization'),
            ),
            array(
                '@type' => 'FAQPage',
                '@id' => $url . '#faq',
                'mainEntity' => $faq_entities,
            ),
        ),
    );
    echo '<script type="application/ld+json">' . wp_json_encode($schema, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . '</script>' . "\n";
}
add_action('wp_head', 'wvn_commercial_head_schema', 31);

function wvn_seed_commercial_seo_pages() {
    if (get_option('_wvn_commercial_seo_pages_v1') === '1') {
        return;
    }
    $pages = wvn_commercial_seo_pages();
    foreach ($pages as $slug => $cfg) {
        $existing = get_page_by_path($slug, OBJECT, 'page');
        if ($existing) {
            continue;
        }
        $page_id = wp_insert_post(wp_slash(array(
            'post_title' => $cfg['title'],
            'post_name' => $slug,
            'post_content' => '<p>' . esc_html($cfg['intro']) . '</p>',
            'post_excerpt' => $cfg['description'],
            'post_status' => 'publish',
            'post_type' => 'page',
            'comment_status' => 'closed',
        )), true);
        if (!is_wp_error($page_id)) {
            update_post_meta($page_id, '_wp_page_template', 'page-wvn-commercial.php');
            update_post_meta($page_id, '_wvn_commercial_seeded', '1');
        }
    }
    update_option('_wvn_commercial_seo_pages_v1', '1', false);
}
add_action('init', 'wvn_seed_commercial_seo_pages', 25);

function wvn_commercial_enqueue_styles() {
    $cfg = wvn_commercial_meta_data();
    if (!$cfg) {
        return;
    }
    wp_enqueue_style('wvn-commercial-seo', get_theme_file_uri('/css/wvn-commercial-seo.css'), array('wvn-overrides'), '1.0.0');
}
add_action('wp_enqueue_scripts', 'wvn_commercial_enqueue_styles', 30);
